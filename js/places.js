// Приводим текст к простому виду для сравнения:
// "Ёлки-Палки, Côte" → "елки палки cote"
function normalizeSearch(text) {
  return String(text)
    .toLowerCase()
    .replace(/ё/g, "е")
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "") // убираем диакритику: é → e
    .replace(/[^a-zа-я0-9]+/g, " ")
    .trim();
}

// Насколько хорошо текст подходит к запросу: 0 — лучше всего, null — не подходит
function matchScore(text, query) {
  const t = normalizeSearch(text);
  if (!query || !t) return null;
  if (t === query) return 0;
  if (t.startsWith(query)) return 1;
  if (t.split(" ").some((word) => word.startsWith(query))) return 2;
  if (t.includes(query)) return 3;
  return null;
}

const collator = new Intl.Collator("ru");

// Список стран строится один раз при загрузке
const COUNTRIES = (() => {
  const ru = new Intl.DisplayNames(["ru"], { type: "region" });
  const en = new Intl.DisplayNames(["en"], { type: "region" });
  return COUNTRY_CODES
    .map((code) => ({
      code,
      name: COUNTRY_NAME_OVERRIDES[code] || ru.of(code),
      en: en.of(code),
      aliases: COUNTRY_ALIASES[code] || [],
    }))
    .filter((c) => c.name && c.name !== c.code) // браузер не знает код — пропускаем
    .sort((a, b) => collator.compare(a.name, b.name));
})();

const COUNTRY_BY_CODE = Object.fromEntries(COUNTRIES.map((c) => [c.code, c]));

function countryName(code) {
  return COUNTRY_BY_CODE[code] ? COUNTRY_BY_CODE[code].name : "";
}

// Найти страну по точному названию (для ручного ввода без выбора из списка)
function findCountryByName(text) {
  const q = normalizeSearch(text);
  if (!q) return null;
  return COUNTRIES.find((c) => [c.name, c.en, ...c.aliases].some((n) => normalizeSearch(n) === q)) || null;
}

// Страны для выпадающего списка.
// Без запроса: { popular, others } — популярные сверху, остальные по алфавиту.
// С запросом: { matches } — подходящие страны, лучшие совпадения первыми.
// Совпадение по городу тоже считается: "Рим" найдёт Италию.
function searchCountries(query) {
  const q = normalizeSearch(query);
  if (!q) {
    const popular = POPULAR_COUNTRY_CODES.map((code) => COUNTRY_BY_CODE[code]).filter(Boolean);
    const popularSet = new Set(POPULAR_COUNTRY_CODES);
    return { popular, others: COUNTRIES.filter((c) => !popularSet.has(c.code)) };
  }

  const matches = [];
  for (const country of COUNTRIES) {
    const nameScores = [country.name, country.en, ...country.aliases]
      .map((n) => matchScore(n, q))
      .filter((s) => s !== null);
    if (nameScores.length) {
      matches.push({ country, score: Math.min(...nameScores), via: null });
      continue;
    }
    const city = (CITIES[country.code] || []).find((c) => {
      const s = matchScore(c, q);
      return s !== null && s <= 2;
    });
    if (city) matches.push({ country, score: 10, via: city });
  }
  // Сначала лучшие совпадения; при равных — популярные направления ("гре" → Греция, а не Гренада)
  const rank = (code) => {
    const i = POPULAR_COUNTRY_CODES.indexOf(code);
    return i === -1 ? POPULAR_COUNTRY_CODES.length : i;
  };
  matches.sort((a, b) => a.score - b.score
    || rank(a.country.code) - rank(b.country.code)
    || collator.compare(a.country.name, b.country.name));
  return { matches };
}

// Города страны: без запроса — все популярные, с запросом — подходящие
function searchCities(code, query) {
  const list = CITIES[code] || [];
  const q = normalizeSearch(query);
  if (!q) return list.slice();
  return list
    .map((city, index) => ({ city, index, score: matchScore(city, q) }))
    .filter((x) => x.score !== null)
    .sort((a, b) => a.score - b.score || a.index - b.index)
    .map((x) => x.city);
}

// Подпись направления: "Рим, Италия", "Италия" или "Рим"
function destinationLabel(city, code) {
  const parts = [String(city || "").trim(), countryName(code)].filter(Boolean);
  return [...new Set(parts)].join(", ");
}
